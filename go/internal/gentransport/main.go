// Command gentransport copies the C transport (c/src/transport.c and
// c/include/transport.h) into go/pkg/transport so the Go build cache tracks
// changes to it. Run `go generate ./pkg/transport` after editing the C code.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

const banner = "/* GENERATED by go/internal/gentransport from %s - DO NOT EDIT. Edit the original and run `go generate ./pkg/transport`. */\n"

func main() {
	root := filepath.Join("..", "..", "..") // run from go/pkg/transport
	pairs := [][2]string{
		{filepath.Join(root, "c", "src", "transport.c"), "transport_impl.c"},
		{filepath.Join(root, "c", "include", "transport.h"), "transport.h"},
	}
	for _, p := range pairs {
		src, err := os.ReadFile(p[0])
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		var out bytes.Buffer
		if p[1] == "transport_impl.c" {
			out.WriteString("//go:build cgo && !nomsquic\n\n")
		}
		fmt.Fprintf(&out, banner, filepath.ToSlash(filepath.Join("c", filepath.Base(filepath.Dir(p[0])), filepath.Base(p[0]))))
		out.Write(src)
		if err := os.WriteFile(p[1], out.Bytes(), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}
